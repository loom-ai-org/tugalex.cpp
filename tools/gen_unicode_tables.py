"""Generate src/unicode_tables.inc from the running Python's Unicode database.

The C++ port must lowercase and strip exactly as Python's ``str.lower`` and
``str.strip`` do, including the Greek final-sigma rule. The tables are taken
from Python itself rather than from ICU, so the two agree on the same Unicode
version; the version is written into the generated file.

Usage: python tools/gen_unicode_tables.py > src/unicode_tables.inc
"""
import sys
import unicodedata

MAX = 0x110000
SIGMA = "Σ"


def ranges(predicate):
    out, start = [], None
    for cp in range(MAX + 1):
        hit = cp < MAX and predicate(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def surrogate(cp):
    return 0xD800 <= cp <= 0xDFFF


def lower_of(cp):
    return chr(cp).lower()


# Case-ignorable and cased are derived from the final-sigma behaviour itself,
# since unicodedata exposes neither property:
#   "A" + c + "Σ" -> ς  iff  ignorable(c) or cased(c)
#   "AΣ" + c      -> ς  iff  ignorable(c) or not cased(c)
#   c + "Σ"       -> ς  iff  cased(c) and not ignorable(c)
def ignorable(cp):
    if surrogate(cp):
        return False
    c = chr(cp)
    return ("A" + c + SIGMA).lower()[-1] == "ς" and ("A" + SIGMA + c).lower()[1] == "ς"


def cased(cp):
    # Only consulted for non-ignorable code points, which is all Python asks.
    if surrogate(cp):
        return False
    return (chr(cp) + SIGMA).lower()[-1] == "ς"


def main():
    w = sys.stdout.write
    w("// Generated by tools/gen_unicode_tables.py; do not edit.\n")
    w(f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.\n\n")

    mappings = [(cp, lower_of(cp)) for cp in range(MAX)
                if not surrogate(cp) and cp != 0x03A3 and lower_of(cp) != chr(cp)]
    w("struct LowerEntry { char32_t cp; char32_t to[3]; unsigned char len; };\n")
    w(f"static const LowerEntry kLower[{len(mappings)}] = {{\n")
    for cp, low in mappings:
        assert len(low) <= 3
        padded = [ord(c) for c in low] + [0] * (3 - len(low))
        w(f"  {{0x{cp:X}, {{0x{padded[0]:X}, 0x{padded[1]:X}, 0x{padded[2]:X}}}, {len(low)}}},\n")
    w("};\n\n")

    for name, pred in (("kSpace", lambda cp: chr(cp).isspace()),
                       ("kCaseIgnorable", ignorable),
                       ("kCased", cased)):
        rs = ranges(pred)
        w(f"static const char32_t {name}[{len(rs)}][2] = {{\n")
        for lo, hi in rs:
            w(f"  {{0x{lo:X}, 0x{hi:X}}},\n")
        w("};\n\n")


if __name__ == "__main__":
    main()
